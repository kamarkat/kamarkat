// HubEnvironmentReconciler converges the hub's own platform state (ADR-117):
//
//   - the escrow of what outlives the cluster (kubeconfigs, Cluster API trust
//     roots, the management-state backup key);
//   - the hub's secrets in OpenBao: Day-0 Secrets copied in, application secrets
//     generated by OpenBao password policies;
//   - one OpenBao static role per declared hub application login role, which
//     generates and rotates that role's password;
//   - the delivered credentials (ESO), before anything that needs them proceeds.
type HubEnvironmentReconciler struct {
	client.Client
	// UncachedClient reads Secrets directly from the API server: the cache strips
	// Secret data.
	UncachedClient client.Client
	Scheme         *runtime.Scheme
	// Store is the box's OpenBao. Nil until the operator has logged in, in which
	// case every phase after the escrow waits.
	Store *secrets.Store
}

