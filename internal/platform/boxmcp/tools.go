func appList(ctx context.Context, c *Clients) (any, error) {
	nss, err := c.Core.CoreV1().Namespaces().List(ctx, metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	var out []map[string]any
	for _, ns := range nss.Items {
		if !strings.HasPrefix(ns.Name, tenantPrefix) {
			continue
		}
		entry := map[string]any{"namespace": ns.Name}
		pods, perr := c.Core.CoreV1().Pods(ns.Name).List(ctx, metav1.ListOptions{})
		if perr != nil {
			entry["pods"] = explain(perr)
		} else {
			ready := 0
			for _, p := range pods.Items {
				if podReady(&p) {
					ready++
				}
			}
			entry["pods"] = fmt.Sprintf("%d/%d ready", ready, len(pods.Items))
		}
		out = append(out, entry)
	}
	return out, nil
}

func podReady(p *corev1.Pod) bool {
	if p.Status.Phase == corev1.PodSucceeded {
		return true
	}
	for _, c := range p.Status.Conditions {
		if c.Type == corev1.PodReady {
			return c.Status == corev1.ConditionTrue
		}
	}
	return false
}

func appStatus(ctx context.Context, c *Clients, namespace string) (any, error) {
	if namespace == "" {
		return nil, fmt.Errorf("namespace is required")
	}
	out := map[string]any{"namespace": namespace}
	if deps, err := c.Core.AppsV1().Deployments(namespace).List(ctx, metav1.ListOptions{}); err == nil {
		var ds []map[string]any
		for _, d := range deps.Items {
			ds = append(ds, map[string]any{"name": d.Name, "ready": fmt.Sprintf("%d/%d", d.Status.ReadyReplicas, d.Status.Replicas)})
		}
		out["deployments"] = ds
	} else {
		out["deployments"] = explain(err)
	}
	if sts, err := c.Core.AppsV1().StatefulSets(namespace).List(ctx, metav1.ListOptions{}); err == nil {
		var ss []map[string]any
		for _, s := range sts.Items {
			ss = append(ss, map[string]any{"name": s.Name, "ready": fmt.Sprintf("%d/%d", s.Status.ReadyReplicas, s.Status.Replicas)})
		}
		out["statefulsets"] = ss
	}
	pods, err := c.Core.CoreV1().Pods(namespace).List(ctx, metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	var ps []map[string]any
	for _, p := range pods.Items {
		var problems []string
		var restarts int32
		for _, cs := range append(append([]corev1.ContainerStatus{}, p.Status.InitContainerStatuses...), p.Status.ContainerStatuses...) {
			restarts += cs.RestartCount
			if w := cs.State.Waiting; w != nil {
				problems = append(problems, fmt.Sprintf("%s waiting: %s %s", cs.Name, w.Reason, truncate(w.Message, 300)))
			}
			if t := cs.LastTerminationState.Terminated; t != nil && t.ExitCode != 0 {
				problems = append(problems, fmt.Sprintf("%s last exited %d: %s", cs.Name, t.ExitCode, t.Reason))
			}
		}
		ps = append(ps, map[string]any{
			"name": p.Name, "phase": string(p.Status.Phase), "ready": podReady(&p),
			"restarts": restarts, "problems": problems,
		})
	}
	out["pods"] = ps
	return out, nil
}

func secretsStatus(ctx context.Context, c *Clients, namespace string) (any, error) {
	if namespace == "" {
		return nil, fmt.Errorf("namespace is required")
	}
	items, err := list(ctx, c, resExternalSecrets, namespace, metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	var out []map[string]any
	for i := range items {
		es := &items[i]
		var keys []string
		data, _, _ := unstructured.NestedSlice(es.Object, "spec", "data")
		for _, d := range data {
			if m, ok := d.(map[string]any); ok {
				keys = append(keys, str(m, "secretKey"))
			}
		}
		out = append(out, map[string]any{
			"externalSecret": es.GetName(),
			"targetSecret":   first(nested(es, "spec", "target", "name"), es.GetName()),
			"keys":           keys,
			"notReady":       notTrue(conditions(es)),
		})
	}
	return out, nil
}

func events(ctx context.Context, c *Clients, in eventsInput) (any, error) {
	if in.Namespace == "" {
		return nil, fmt.Errorf("namespace is required")
	}
	evs, err := c.Core.CoreV1().Events(in.Namespace).List(ctx, metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	items := evs.Items
	sort.Slice(items, func(i, j int) bool { return items[i].LastTimestamp.After(items[j].LastTimestamp.Time) })
	var out []map[string]any
	for _, e := range items {
		if in.WarningsOnly && e.Type != corev1.EventTypeWarning {
			continue
		}
		out = append(out, map[string]any{
			"type": e.Type, "reason": e.Reason, "object": e.InvolvedObject.Kind + "/" + e.InvolvedObject.Name,
			"message": truncate(e.Message, 400), "count": e.Count, "last": e.LastTimestamp.Format("2006-01-02T15:04:05Z07:00"),
		})
		if len(out) == 100 {
			break
		}
	}
	return out, nil
}

func workloadLogs(ctx context.Context, c *Clients, in logsInput) (any, error) {
	if in.Namespace == "" || in.Pod == "" {
		return nil, fmt.Errorf("namespace and pod are required")
	}
	lines := in.Lines
	if lines <= 0 {
		lines = 200
	}
	if lines > maxLogLines {
		lines = maxLogLines
	}
	limit := int64(maxLogBytes)
	req := c.Core.CoreV1().Pods(in.Namespace).GetLogs(in.Pod, &corev1.PodLogOptions{
		Container: in.Container, TailLines: &lines, Previous: in.Previous, LimitBytes: &limit, Timestamps: true,
	})
	stream, err := req.Stream(ctx)
	if err != nil {
		return nil, err
	}
	defer func() { _ = stream.Close() }()
	var buf bytes.Buffer
	if _, err := io.Copy(&buf, io.LimitReader(stream, maxLogBytes)); err != nil {
		return nil, err
	}
	return map[string]any{"namespace": in.Namespace, "pod": in.Pod, "container": in.Container, "log": buf.String()}, nil
}

// ── certs ───────────────────────────────────────────────────────────────────

func certificates(ctx context.Context, c *Clients, in certInput) (any, error) {
	items, err := list(ctx, c, resCertificates, in.Namespace, metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	var out []map[string]any
	for i := range items {
		cert := &items[i]
		ready := "Unknown"
		var reason string
		for _, cond := range conditions(cert) {
			if cond.Type == "Ready" {
				ready, reason = cond.Status, first(cond.Message, cond.Reason)
			}
		}
		if in.NotReady && ready == "True" {
			continue
		}
		out = append(out, map[string]any{
			"name": cert.GetName(), "namespace": cert.GetNamespace(), "ready": ready, "reason": truncate(reason, 300),
			"notAfter": nested(cert, "status", "notAfter"), "renewalTime": nested(cert, "status", "renewalTime"),
			"issuer": nested(cert, "spec", "issuerRef", "name"),
		})
	}
	return out, nil
}

// ── backups ─────────────────────────────────────────────────────────────────

func backups(ctx context.Context, c *Clients) (any, error) {
	items, err := list(ctx, c, resCNPGClusters, "", metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	var out []map[string]any
	for i := range items {
		db := &items[i]
		archiving := "Unknown"
		var archivingMsg string
		for _, cond := range conditions(db) {
			if cond.Type == "ContinuousArchiving" {
				archiving, archivingMsg = cond.Status, cond.Message
			}
		}
		last := nested(db, "status", "lastSuccessfulBackup")
		out = append(out, map[string]any{
			"cluster": db.GetName(), "namespace": db.GetNamespace(),
			"phase":                nested(db, "status", "phase"),
			"lastSuccessfulBackup": last, "lastBackupAge": age(last),
			"firstRecoverabilityPoint": nested(db, "status", "firstRecoverabilityPoint"),
			"continuousArchiving":      archiving, "archivingMessage": truncate(archivingMsg, 300),
			"backupConfigured": nested(db, "spec", "backup") != "",
		})
	}
	return out, nil
}

// ── envs ────────────────────────────────────────────────────────────────────

func envList(ctx context.Context, c *Clients) (any, error) {
	pools, err := list(ctx, c, resSpokePools, "", metav1.ListOptions{LabelSelector: "kamarkat.io/ephemeral=true"})
	if err != nil {
		return nil, err
	}
	var out []map[string]any
	for i := range pools {
		p := &pools[i]
		out = append(out, map[string]any{
			"name": p.GetName(), "labels": p.GetLabels(), "created": p.GetCreationTimestamp().Format("2006-01-02T15:04:05Z07:00"),
			"notReady": notTrue(conditions(p)),
		})
	}
	if len(out) == 0 {
		return map[string]any{"environments": []any{}, "note": "no ephemeral environments are declared on this box"}, nil
	}
	return out, nil
}
