// ── box ─────────────────────────────────────────────────────────────────────

func describeBox(ctx context.Context, c *Clients) (any, error) {
	out := map[string]any{}
	if hubs, err := list(ctx, c, resHubEnvironments, "", metav1.ListOptions{}); err == nil {
		var envs []map[string]any
		for i := range hubs {
			envs = append(envs, map[string]any{
				"name":       hubs[i].GetName(),
				"phase":      nested(&hubs[i], "status", "phase"),
				"conditions": conditions(&hubs[i]),
			})
		}
		out["hubEnvironments"] = envs
	} else {
		out["hubEnvironments"] = explain(err)
	}
	apps, err := list(ctx, c, resApplications, "", metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	healthy := 0
	var bundles []map[string]string
	for i := range apps {
		a := &apps[i]
		if nested(a, "status", "sync", "status") == "Synced" && nested(a, "status", "health", "status") == "Healthy" {
			healthy++
		}
		if strings.HasSuffix(a.GetName(), "-platform") {
			for _, s := range sources(a) {
				if s["chart"] != "" {
					bundles = append(bundles, map[string]string{"application": a.GetName(), "chart": s["chart"], "version": s["targetRevision"]})
				}
			}
		}
	}
	out["platformBundle"] = bundles
	out["applications"] = map[string]int{"total": len(apps), "syncedAndHealthy": healthy}
	return out, nil
}

func sources(a *unstructured.Unstructured) []map[string]string {
	var out []map[string]string
	read := func(m map[string]any) {
		out = append(out, map[string]string{
			"repoURL":        str(m, "repoURL"),
			"chart":          str(m, "chart"),
			"path":           str(m, "path"),
			"targetRevision": str(m, "targetRevision"),
		})
	}
	if s, ok, _ := unstructured.NestedMap(a.Object, "spec", "source"); ok {
		read(s)
	}
	if ss, ok, _ := unstructured.NestedSlice(a.Object, "spec", "sources"); ok {
		for _, s := range ss {
			if m, ok := s.(map[string]any); ok {
				read(m)
			}
		}
	}
	return out
}

// ── clusters ────────────────────────────────────────────────────────────────

func listClusters(ctx context.Context, c *Clients) (any, error) {
	out := map[string]any{}
	if pools, err := list(ctx, c, resSpokePools, "", metav1.ListOptions{}); err == nil {
		var claims []map[string]any
		for i := range pools {
			p := &pools[i]
			claims = append(claims, map[string]any{
				"name":        p.GetName(),
				"environment": p.GetLabels()["environment"],
				"provider":    nested(p, "spec", "provider"),
				"region":      nested(p, "spec", "region"),
				"nodes":       nested(p, "spec", "nodePool", "count"),
				"notReady":    notTrue(conditions(p)),
			})
		}
		out["managedClusterClaims"] = claims
	} else {
		out["managedClusterClaims"] = explain(err)
	}
	if capi, err := list(ctx, c, resCAPIClusters, "", metav1.ListOptions{}); err == nil {
		var clusters []map[string]any
		for i := range capi {
			k := &capi[i]
			clusters = append(clusters, map[string]any{
				"name":      k.GetName(),
				"namespace": k.GetNamespace(),
				"phase":     nested(k, "status", "phase"),
				"notReady":  notTrue(conditions(k)),
			})
		}
		out["capiClusters"] = clusters
	} else {
		out["capiClusters"] = explain(err)
	}
	return out, nil
}

func clusterStatus(ctx context.Context, c *Clients, name string) (any, error) {
	if name == "" {
		return nil, fmt.Errorf("cluster is required")
	}
	out := map[string]any{"cluster": name, "note": "convergence: the cluster's own report. Acceptance is cluster_acceptance."}
	if pool, err := get(ctx, c, resSpokePools, "", name); err == nil {
		out["claim"] = map[string]any{"spec": pool.Object["spec"], "conditions": conditions(pool)}
	} else {
		out["claim"] = explain(err)
	}
	capi, err := list(ctx, c, resCAPIClusters, "", metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	for i := range capi {
		k := &capi[i]
		if k.GetName() != name && k.GetLabels()["cluster-name"] != name {
			continue
		}
		out["capiCluster"] = map[string]any{
			"namespace":  k.GetNamespace(),
			"phase":      nested(k, "status", "phase"),
			"conditions": conditions(k),
		}
		machines, merr := list(ctx, c, resCAPIMachines, k.GetNamespace(), metav1.ListOptions{LabelSelector: "cluster.x-k8s.io/cluster-name=" + k.GetName()})
		if merr != nil {
			out["machines"] = explain(merr)
			break
		}
		var ms []map[string]any
		for j := range machines {
			m := &machines[j]
			ms = append(ms, map[string]any{
				"name":     m.GetName(),
				"phase":    nested(m, "status", "phase"),
				"node":     nested(m, "status", "nodeRef", "name"),
				"notReady": notTrue(conditions(m)),
			})
		}
		out["machines"] = ms
		break
	}
	return out, nil
}

func clusterAcceptance(ctx context.Context, c *Clients, name string) (any, error) {
	hubs, err := list(ctx, c, resHubEnvironments, "", metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	for i := range hubs {
		for _, cond := range conditions(&hubs[i]) {
			if strings.Contains(strings.ToLower(cond.Type), "accept") {
				return map[string]any{"cluster": name, "source": "HubEnvironment/" + hubs[i].GetName(), "acceptance": cond}, nil
			}
		}
	}
	return map[string]any{
		"cluster":  name,
		"verdict":  "unknown",
		"why":      "this box does not surface an acceptance condition in the cluster (ADR-115 §11): the verdict is the report of the last `kakt verify` run",
		"whereNow": "the Bootstrap cluster workflow's validation artefact, or registry/clusters/<mgmt>/.state/logs in the box repository; or have the person run `kakt verify --cluster " + name + "`",
	}, nil
}

// ── gitops ──────────────────────────────────────────────────────────────────

func boundaryOf(a *unstructured.Unstructured) string {
	for _, o := range a.GetOwnerReferences() {
		if o.Kind == "ApplicationSet" {
			return o.Name
		}
	}
	return ""
}

func argoApps(ctx context.Context, c *Clients, in appsFilterInput) (any, error) {
	apps, err := list(ctx, c, resApplications, "", metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	var out []map[string]any
	for i := range apps {
		a := &apps[i]
		b := boundaryOf(a)
		if in.Boundary != "" && !strings.HasPrefix(b, in.Boundary) {
			continue
		}
		sync, health := nested(a, "status", "sync", "status"), nested(a, "status", "health", "status")
		if in.Unhealthy && sync == "Synced" && health == "Healthy" {
			continue
		}
		out = append(out, map[string]any{
			"name": a.GetName(), "namespace": a.GetNamespace(), "boundary": b,
			"sync": sync, "health": health,
			"operation": nested(a, "status", "operationState", "phase"),
		})
	}
	return out, nil
}

func argoAppStatus(ctx context.Context, c *Clients, in appInput) (any, error) {
	var app *unstructured.Unstructured
	if in.Namespace != "" {
		a, err := get(ctx, c, resApplications, in.Namespace, in.Name)
		if err != nil {
			return nil, err
		}
		app = a
	} else {
		apps, err := list(ctx, c, resApplications, "", metav1.ListOptions{})
		if err != nil {
			return nil, err
		}
		for i := range apps {
			if apps[i].GetName() == in.Name {
				app = &apps[i]
				break
			}
		}
		if app == nil {
			return nil, fmt.Errorf("no Application named %q", in.Name)
		}
	}
	var unhealthy []map[string]string
	resources, _, _ := unstructured.NestedSlice(app.Object, "status", "resources")
	for _, r := range resources {
		m, ok := r.(map[string]any)
		if !ok {
			continue
		}
		health, _ := m["health"].(map[string]any)
		hs := ""
		if health != nil {
			hs = str(health, "status")
		}
		if str(m, "status") == "Synced" && (hs == "" || hs == "Healthy") {
			continue
		}
		hm := ""
		if health != nil {
			hm = str(health, "message")
		}
		unhealthy = append(unhealthy, map[string]string{
			"kind": str(m, "kind"), "namespace": str(m, "namespace"), "name": str(m, "name"),
			"sync": str(m, "status"), "health": hs, "message": truncate(hm, 400),
		})
	}
	return map[string]any{
		"name": app.GetName(), "namespace": app.GetNamespace(), "boundary": boundaryOf(app),
		"sync":       nested(app, "status", "sync", "status"),
		"revision":   nested(app, "status", "sync", "revision"),
		"health":     nested(app, "status", "health", "status"),
		"conditions": conditions(app, "status", "conditions"),
		"operation": map[string]string{
			"phase":    nested(app, "status", "operationState", "phase"),
			"message":  truncate(nested(app, "status", "operationState", "message"), 800),
			"finished": nested(app, "status", "operationState", "finishedAt"),
		},
		"sources":           sources(app),
		"resourcesNotReady": unhealthy,
	}, nil
}

// ── platform ────────────────────────────────────────────────────────────────

func boundaryStatus(ctx context.Context, c *Clients) (any, error) {
	sets, err := list(ctx, c, resApplicationSets, "", metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	apps, err := list(ctx, c, resApplications, "", metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	type summary struct {
		Boundary         string      `json:"boundary"`
		Applications     int         `json:"applications"`
		SyncedAndHealthy int         `json:"syncedAndHealthy"`
		NotReady         []string    `json:"notReady,omitempty"`
		Conditions       []Condition `json:"conditionsNotTrue,omitempty"`
	}
	byName := map[string]*summary{}
	var order []string
	for i := range sets {
		n := sets[i].GetName()
		byName[n] = &summary{Boundary: n, Conditions: notErrorFree(conditions(&sets[i]))}
		order = append(order, n)
	}
	for i := range apps {
		a := &apps[i]
		s, ok := byName[boundaryOf(a)]
		if !ok {
			continue
		}
		s.Applications++
		if nested(a, "status", "sync", "status") == "Synced" && nested(a, "status", "health", "status") == "Healthy" {
			s.SyncedAndHealthy++
		} else {
			s.NotReady = append(s.NotReady, fmt.Sprintf("%s (%s/%s)", a.GetName(), nested(a, "status", "sync", "status"), nested(a, "status", "health", "status")))
		}
	}
	sort.Strings(order)
	out := make([]*summary, 0, len(order))
	for _, n := range order {
		out = append(out, byName[n])
	}
	return out, nil
}

// notErrorFree keeps the ApplicationSet conditions worth reading: any error, and
// ResourcesUpToDate when it is not True.
func notErrorFree(cs []Condition) []Condition {
	var out []Condition
	for _, c := range cs {
		if (strings.Contains(c.Type, "Error") && c.Status == "True") || (!strings.Contains(c.Type, "Error") && c.Status != "True") {
			out = append(out, c)
		}
	}
	return out
}

