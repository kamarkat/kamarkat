func policyViolations(ctx context.Context, c *Clients) (any, error) {
	var out []map[string]string
	collect := func(items []unstructured.Unstructured) {
		for i := range items {
			results, _, _ := unstructured.NestedSlice(items[i].Object, "results")
			for _, r := range results {
				m, ok := r.(map[string]any)
				if !ok || str(m, "result") != "fail" {
					continue
				}
				var res []string
				if rs, ok := m["resources"].([]any); ok {
					for _, x := range rs {
						if rm, ok := x.(map[string]any); ok {
							res = append(res, strings.Trim(str(rm, "kind")+" "+str(rm, "namespace")+"/"+str(rm, "name"), " /"))
						}
					}
				}
				out = append(out, map[string]string{
					"policy": str(m, "policy"), "rule": str(m, "rule"), "severity": str(m, "severity"),
					"message": truncate(str(m, "message"), 400), "resources": strings.Join(res, ", "),
				})
			}
		}
	}
	ns, err := list(ctx, c, resPolicyReports, "", metav1.ListOptions{})
	if err != nil {
		return nil, err
	}
	collect(ns)
	if cl, err := list(ctx, c, resClusterReports, "", metav1.ListOptions{}); err == nil {
		collect(cl)
	}
	return map[string]any{"failed": len(out), "results": out}, nil
}

