// The Application over clusters/<name>/generated/ must never prune.
//
// That directory holds hub-cluster.yaml, the CAPI Cluster describing the machines
// the box runs on. Pruning it tells ArgoCD to delete the Cluster, and CAPI answers
// by destroying every node including the control plane -- so a deleted file, a bad
// rebase or a renamed directory would take out the estate. Nothing else in a
// tenant's repository has that reach, and the cost of leaving prune off is a stale
// generated artifact.
//
// selfHeal must stay on: it is what makes the file authoritative over a `kubectl
// edit`, which is the whole point of recording the topology in Git.
func TestGeneratedApplicationNeverPrunes(t *testing.T) {
	root := repoRootForTest(t)
	base := filepath.Join(root, "manifests", "tenants", "gitops-template", "templates")

	// The management cluster's own, a flat file its root applies.
	path := filepath.Join(base, "mgmt", "generated.yaml")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%s: %v", path, err)
	}
	// The template carries scaffolding placeholders, which are not YAML values
	// but are lexically fine as scalars, so it parses as-is.
	var app struct {
		Spec struct {
			SyncPolicy struct {
				Automated struct {
					Prune    bool `yaml:"prune"`
					SelfHeal bool `yaml:"selfHeal"`
				} `yaml:"automated"`
			} `yaml:"syncPolicy"`
		} `yaml:"spec"`
	}
	if err := yaml.Unmarshal(raw, &app); err != nil {
		t.Fatalf("%s: parse: %v", path, err)
	}
	if app.Spec.SyncPolicy.Automated.Prune {
		t.Error("the management cluster's generated Application prunes. That directory " +
			"holds hub-cluster.yaml, the CAPI Cluster describing the machines the box " +
			"runs on, and pruning it destroys every node including the control plane.")
	}
	if !app.Spec.SyncPolicy.Automated.SelfHeal {
		t.Error("it does not self-heal, so a kubectl edit of the topology would outlive " +
			"what Git says and capacity would have two sources.")
	}

	// A workload cluster's is generated by an ApplicationSet, so the same two
	// properties are asserted there -- plus the deletion policy, which is the
	// whole lifecycle: see TestWorkloadClusterLifecycleIsItsClaim.
	for _, set := range workloadClusterAppSets(t) {
		if set.Spec.Template.Spec.SyncPolicy.Automated.Prune {
			t.Errorf("%s generates a pruning Application", set.Metadata.Name)
		}
		if !set.Spec.Template.Spec.SyncPolicy.Automated.SelfHeal {
			t.Errorf("%s generates an Application that does not self-heal", set.Metadata.Name)
		}
	}
}

// applicationSet is the shape these tests read: enough of an ApplicationSet to
// assert the lifecycle contract, and nothing more.
type applicationSet struct {
	Metadata struct {
		Name string `yaml:"name"`
	} `yaml:"metadata"`
	Spec struct {
		SyncPolicy struct {
			PreserveResourcesOnDeletion bool `yaml:"preserveResourcesOnDeletion"`
		} `yaml:"syncPolicy"`
		Generators []struct {
			Git struct {
				Files []struct {
					Path string `yaml:"path"`
				} `yaml:"files"`
				Directories []struct {
					Path string `yaml:"path"`
				} `yaml:"directories"`
			} `yaml:"git"`
		} `yaml:"generators"`
		Template struct {
			Metadata struct {
				Name       string   `yaml:"name"`
				Finalizers []string `yaml:"finalizers"`
			} `yaml:"metadata"`
			Spec struct {
				Source struct {
					Path string `yaml:"path"`
				} `yaml:"source"`
				Destination struct {
					Name   string `yaml:"name"`
					Server string `yaml:"server"`
				} `yaml:"destination"`
				SyncPolicy struct {
					Automated struct {
						Prune    bool `yaml:"prune"`
						SelfHeal bool `yaml:"selfHeal"`
					} `yaml:"automated"`
				} `yaml:"syncPolicy"`
			} `yaml:"spec"`
		} `yaml:"template"`
	} `yaml:"spec"`
}

// workloadClusterAppSets reads the pair that owns a workload cluster's lifecycle.
func workloadClusterAppSets(t *testing.T) []applicationSet {
	t.Helper()
	path := filepath.Join(repoRootForTest(t), "manifests", "tenants", "gitops-template",
		"templates", "mgmt", "workload-clusters.yaml")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%s: %v", path, err)
	}
	var sets []applicationSet
	dec := yaml.NewDecoder(strings.NewReader(string(raw)))
	for {
		var set applicationSet
		err := dec.Decode(&set)
		if err != nil {
			break
		}
		if set.Metadata.Name != "" {
			sets = append(sets, set)
		}
	}
	if len(sets) != 2 {
		t.Fatalf("%s declares %d ApplicationSet(s), want 2", path, len(sets))
	}
	return sets
}

// A WORKLOAD CLUSTER EXISTS BECAUSE ITS CLAIM FILE DOES, and the deletion
// contract is the asymmetry between these two sets.
//
// The infrastructure set must NOT preserve: when the claim file goes, the
// generated Application is deleted with Argo CD's resources-finalizer, the claim
// goes with it, and Crossplane and Cluster API unwind the cluster. That is the
// removal, and it is a commit.
//
// The generated set MUST preserve: every resource it holds is addressed to the
// workload cluster that is being destroyed, so a cascade there buys nothing and
// blocks on an API server that is already gone.
//
// Neither template may hardcode the resources-finalizer.
// preserveResourcesOnDeletion is what adds or withholds it, so writing it twice
// is how the two come to disagree.
func TestWorkloadClusterLifecycleIsItsClaim(t *testing.T) {
	const claim = "registry/clusters/*/infrastructure/spokepool.yaml"
	for _, set := range workloadClusterAppSets(t) {
		name := set.Metadata.Name
		if len(set.Spec.Generators) != 1 {
			t.Fatalf("%s has %d generators; the claim file is the one input",
				name, len(set.Spec.Generators))
		}
		g := set.Spec.Generators[0].Git
		if len(g.Directories) > 0 {
			t.Errorf("%s generates from directories: a stray file left beside a removed "+
				"claim would keep the directory, and the cluster, alive", name)
		}
		if len(g.Files) != 1 || g.Files[0].Path != claim {
			t.Errorf("%s generates from %v, want the claim file %q", name, g.Files, claim)
		}
		if fin := set.Spec.Template.Metadata.Finalizers; len(fin) != 0 {
			t.Errorf("%s hardcodes finalizers %v; preserveResourcesOnDeletion decides that",
				name, fin)
		}

		switch {
		case strings.HasSuffix(set.Spec.Template.Metadata.Name, "-infrastructure"):
			if set.Spec.SyncPolicy.PreserveResourcesOnDeletion {
				t.Errorf("%s preserves resources: removing the claim would delete the "+
					"Application and leave the cluster running, which is the state the "+
					"withdrawn --destroy step existed to close", name)
			}
			if set.Spec.Template.Spec.Destination.Server == "" {
				t.Errorf("%s does not address the management cluster, which is the only "+
					"cluster that can reconcile a claim for one that does not exist yet", name)
			}
		case strings.HasSuffix(set.Spec.Template.Metadata.Name, "-generated"):
			if !set.Spec.SyncPolicy.PreserveResourcesOnDeletion {
				t.Errorf("%s does not preserve resources: its contents live on the cluster "+
					"being destroyed, so the cascade would block on an API that is gone", name)
			}
			// Addressed to the workload cluster, which is what makes preserving
			// safe: nothing of the management cluster's is in this set.
			if set.Spec.Template.Spec.Destination.Server != "" {
				t.Errorf("%s is addressed in-cluster; preserving its resources would then "+
					"orphan objects on the MANAGEMENT cluster", name)
			}
			if set.Spec.Template.Spec.Destination.Name == "" {
				t.Errorf("%s does not name the workload cluster as its destination", name)
			}
		default:
			t.Errorf("%s generates %q, which is neither of the two Applications a "+
				"management cluster holds for a workload cluster",
				name, set.Spec.Template.Metadata.Name)
		}
	}
}

// The claim is one document, because a git files generator parses the file it
// matched to build its parameters and a multi-document stream is not parseable
// as one. The Namespace that used to share the file lives beside it.
func TestClaimTemplatesAreSingleDocuments(t *testing.T) {
	base := filepath.Join(repoRootForTest(t), "manifests", "tenants", "gitops-template",
		"templates", "workload-cluster", "infrastructure")
	entries, err := os.ReadDir(base)
	if err != nil {
		t.Fatal(err)
	}
	var claims int
	for _, e := range entries {
		if !strings.HasPrefix(e.Name(), "spokepool-") {
			continue
		}
		claims++
		raw, err := os.ReadFile(filepath.Join(base, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		if n := strings.Count(string(raw), "\n---"); n != 0 {
			t.Errorf("%s holds %d extra document(s); the generator would fail to parse it "+
				"and the cluster would never be generated", e.Name(), n)
		}
	}
	if claims == 0 {
		t.Error("no claim template; nothing declares a workload cluster")
	}
}

// The file Day-0 writes must warn against the one edit that wedges a cluster.
func TestRecordedTopologyWarnsAboutAutoscalerAnnotations(t *testing.T) {
	root := repoRootForTest(t)
	raw, err := os.ReadFile(filepath.Join(root,
		"internal", "kakt-cli", "cluster", "provisioner.go"))
	if err != nil {
		t.Fatalf("read provisioner: %v", err)
	}
	src := string(raw)
	for _, want := range []string{
		"cluster-api-autoscaler-node-group-",
		"replicas",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("the recorded topology header no longer mentions %q; CAPI rejects "+
				"a topology carrying both replicas and the autoscaler bounds, and that "+
				"rejection wedges the object", want)
		}
	}
}

// The names a teardown stops are the names the template declares.
//
// A teardown has to stop these two sets regenerating a cluster it is destroying,
// and it stops them BY NAME. A name that drifted from the template would leave
// the set running: the delete would appear to work, and the platform would
// rebuild the cluster under a name whose secret path and backup prefix belong to
// the one just destroyed.
func TestAppSetNamesMatchTheTemplate(t *testing.T) {
	const mgmt = "acme-hub"
	declared := map[string]bool{}
	for _, set := range workloadClusterAppSets(t) {
		declared[strings.Replace(set.Metadata.Name, "<CLUSTER_NAME>", mgmt, 1)] = true
	}
	for _, name := range WorkloadClusterAppSets(mgmt) {
		if !declared[name] {
			t.Errorf("teardown stops %q, which no ApplicationSet in the template is called; "+
				"declared: %v", name, declared)
		}
	}
	if len(declared) != len(WorkloadClusterAppSets(mgmt)) {
		t.Errorf("the template declares %d sets, teardown knows %d",
			len(declared), len(WorkloadClusterAppSets(mgmt)))
	}
}
