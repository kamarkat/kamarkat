#!/usr/bin/env python3
"""Every hub database role has exactly one password authority.

ADR-023/ADR-112 amendment (2026-11-24). hub-operator generates the credential,
Infisical stores it, ESO delivers it, and CloudNativePG is the only thing that
writes it into PostgreSQL.

Two authorities wrote the same field before this: CNPG reconciles the application
owner from the Secret GetApplicationSecretName() resolves -- on every instance
reconcile, not only at bootstrap -- while hub-operator issued ALTER ROLE from the
Infisical value. Whichever ran last won. On nutgraf-mgmt-1794929668 that left
hub_zitadel holding CNPG's generated bootstrap password while Zitadel presented
Infisical's, so authentication failed directly and through the pooler, and
DatabaseRolesProvisioned=True throughout because it checked existence, not
agreement.

Three assertions, each of which the incident needed to be false:
  1. Every Cluster names its authoritative owner Secret, so CNPG has one source.
  2. That Secret satisfies CNPG's contract: basic-auth, username equal to the
     Cluster's owner, cnpg.io/reload.
  3. hub-operator issues no password-changing SQL.
"""
import re
import sys
from pathlib import Path

HUB = Path("manifests/hub-core-services")
ROLES_GO = Path("operators/hub-operator/internal/database/roles.go")
CONTROLLER = Path("operators/hub-operator/internal/controller/hubenvironment_controller.go")

out = []
def ok(m): out.append(("OK", m))
def bad(m): out.append(("BAD", m))


def clusters():
    """Every CNPG Cluster declared under hub-core-services, with its owner."""
    found = {}
    for f in HUB.rglob("*-db.yaml"):
        text = f.read_text()
        if "kind: Cluster" not in text:
            continue
        owner = re.search(r"\n\s+owner:\s*(\S+)", text)
        secret = re.search(r"\n\s+secret:\s*\n\s+name:\s*(\S+)", text)
        found[f] = (owner.group(1) if owner else None,
                    secret.group(1) if secret else None)
    return found


def main():
    found = clusters()
    if not found:
        bad(f"no CNPG Clusters found under {HUB}; this check cannot see what it guards")
        return

    unpinned = []
    for f, (owner, secret) in sorted(found.items()):
        if owner is None:
            bad(f"{f.name} declares a Cluster with no initdb owner; this check cannot "
                f"tell which role its credential belongs to")
            continue
        if secret is None:
            unpinned.append(f"{f.name} (owner {owner})")
            continue

        # The Secret CNPG will read must satisfy its contract, or it is ignored and
        # CNPG silently keeps its own generated password.
        es = next((p for p in HUB.rglob("*.yaml")
                   if re.search(rf"\n\s+name:\s*{re.escape(secret)}\s*\n", p.read_text())
                   and "kind: ExternalSecret" in p.read_text()), None)
        if es is None:
            # NOT EVERY OWNER SECRET COMES FROM ESO. infisical-db's is generated by
            # hub-operator during Day-0, before boundary 02 reconciles, because the
            # box's own secret store cannot deliver the credential its own database
            # needs (ADR-112 §7). That is the bootstrap contract and it is preserved.
            # It still has exactly one authority, which is what this check is for.
            if re.search(rf'"{re.escape(secret)}"', ROLES_GO.read_text()) or \
               any(re.search(rf'"{re.escape(secret)}"', g.read_text())
                   for g in Path("operators/hub-operator/internal").rglob("*.go")):
                ok(f"{f.name}: CNPG reconciles {owner} from {secret}, which hub-operator "
                   f"generates during Day-0 (the bootstrap contract, ADR-112 §7)")
            else:
                bad(f"{f.name} names {secret} as its application-owner Secret and nothing "
                    f"delivers or generates it: CNPG would find nothing and keep the "
                    f"password it generated")
            continue
        text = es.read_text()
        problems = []
        # The FIELD, not the string. These files explain the contract in prose, so
        # a substring match passed while the actual type said Opaque -- the check
        # would have agreed with a Secret CNPG ignores. Caught by mutation.
        if not re.search(r"\n\s+type:\s*kubernetes\.io/basic-auth\s*\n", text):
            problems.append("not type kubernetes.io/basic-auth, which CNPG ignores")
        if f'cnpg.io/reload: "true"' not in text:
            problems.append("no cnpg.io/reload, so a rotation waits for the next resync")
        if not re.search(rf'username:\s*"{re.escape(owner)}"', text):
            problems.append(f"username is not the literal {owner!r}; CNPG takes the role "
                            f"name from the Secret, so a mismatch repoints it at another role")
        if problems:
            bad(f"{es.name} does not satisfy CNPG's password contract: {'; '.join(problems)}")
        else:
            ok(f"{f.name}: CNPG reconciles {owner} from {secret}, which satisfies its contract")

    if unpinned:
        bad(f"Cluster(s) with no authoritative owner Secret: {', '.join(unpinned)}. CNPG "
            f"then generates and reconciles its own password for that role, and anything "
            f"else that sets it is a competing authority")

    # No password-changing SQL anywhere in hub-operator.
    writers = []
    for src in (ROLES_GO, CONTROLLER):
        for m in re.finditer(r'"(ALTER ROLE[^"]*PASSWORD[^"]*)"', src.read_text()):
            writers.append(f"{src.name}: {m.group(1)[:40]}")
    if writers:
        bad(f"hub-operator still issues password-changing SQL ({'; '.join(writers)}): that is "
            f"a second authority for a field CloudNativePG reconciles")
    else:
        ok("hub-operator issues no password-changing SQL; CloudNativePG is the sole writer")

    # Readiness must distinguish existence from agreement.
    if "RolesDisagreeingWithSecret" not in CONTROLLER.read_text():
        bad("DatabaseRolesProvisioned does not compare roles against their Secrets, so a "
            "role that exists with the wrong password reports as provisioned -- the "
            "false green the outage ran under")
    else:
        ok("readiness compares each role against its authoritative Secret, so existence "
           "is not reported as agreement")


main()
for level, message in out:
    print(f"{level}\t{message}")
