#!/usr/bin/env bash
# Render this release's Homebrew formula and push it to the tap.
#
# WRITTEN BY THE PIPELINE, NEVER BY HAND. A kakt release carries a platform
# version, so a formula updated separately gives `brew install` a CLI whose
# bundle version disagrees with the newest published bundle -- and nothing on the
# user's machine says so. One authority, updated by the thing that publishes.
#
# The formula installs the RELEASE BINARY rather than building from source. That
# is why this belongs in a tap and not in homebrew/core, whose policy requires a
# formula to build from source or install platform-independent output. A source
# build also has to inject the version, and a build that forgets reports
# `development` and reads platform content from the working directory (ADR-068).
#
# STABLE ONLY by default. An rc is a version consumed by testing; a tap that
# moves to one hands `brew install` a prerelease CLI carrying a prerelease
# platform. --allow-prerelease is there for a deliberate exception.
set -euo pipefail

VERSION="${1:?usage: update-homebrew-tap.sh <version> [bindir]}"
BINDIR="${2:-dist/bin}"
TAP_REPO="${HOMEBREW_TAP_REPO:-kamarkat/homebrew-tap}"
ALLOW_PRERELEASE=0
[ "${3:-}" = "--allow-prerelease" ] && ALLOW_PRERELEASE=1

case "$VERSION" in
    *-*)
        if [ "$ALLOW_PRERELEASE" != 1 ]; then
            echo "homebrew-tap: ${VERSION} is a prerelease; the tap tracks stable releases."
            echo "              Nothing was pushed."
            exit 0
        fi
        ;;
esac

: "${HOMEBREW_TAP_TOKEN:?a token with Contents:write on ${TAP_REPO} is required}"

sums="$BINDIR/SHA256SUMS"
[ -f "$sums" ] || {
    echo "homebrew-tap: no $sums, so the formula would carry no checksums." >&2
    echo "  The release workflow writes it before this runs." >&2
    exit 1
}

# One sha per published binary, read from the file the release publishes rather
# than recomputed here: the formula then verifies exactly what a tenant
# downloads, and a mismatch between the two cannot arise.
sha_for() {
    local asset="$1" sha
    sha=$(awk -v a="$asset" '$2 == a {print $1}' "$sums")
    [ -n "$sha" ] || { echo "homebrew-tap: $sums does not list $asset" >&2; exit 1; }
    printf '%s' "$sha"
}
darwin_arm=$(sha_for kakt-darwin-arm64)
darwin_amd=$(sha_for kakt-darwin-amd64)
linux_arm=$(sha_for kakt-linux-arm64)
linux_amd=$(sha_for kakt-linux-amd64)

base="https://github.com/kamarkat/kamarkat/releases/download/v${VERSION}"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# HOMEBREW_TAP_URL overrides where the tap lives, for a GitHub Enterprise host
# or a local checkout. The default is the token-authenticated https remote.
tap_url="${HOMEBREW_TAP_URL:-https://x-access-token:${HOMEBREW_TAP_TOKEN}@github.com/${TAP_REPO}.git}"
git clone -q --depth 1 "$tap_url" "$work/tap" || {
    echo "homebrew-tap: could not clone ${TAP_REPO}." >&2
    echo "  It must exist and HOMEBREW_TAP_TOKEN must have Contents:write on it." >&2
    exit 1
}

mkdir -p "$work/tap/Formula"
cat > "$work/tap/Formula/kakt.rb" <<FORMULA
# Generated by scripts/package/update-homebrew-tap.sh in kamarkat/kamarkat.
# Edits here are overwritten by the next release.
class Kakt < Formula
  desc "Establishes an enterprise-grade cloud platform in your own infrastructure"
  homepage "https://github.com/kamarkat/kamarkat"
  version "${VERSION}"

  on_macos do
    on_arm do
      url "${base}/kakt-darwin-arm64"
      sha256 "${darwin_arm}"
    end
    on_intel do
      url "${base}/kakt-darwin-amd64"
      sha256 "${darwin_amd}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/kakt-linux-arm64"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/kakt-linux-amd64"
      sha256 "${linux_amd}"
    end
  end

  def install
    bin.install Dir["kakt-*"].first => "kakt"
  end

  # The version the binary CARRIES, not the version Homebrew installed. They are
  # the same string by construction in a released build and differ in a build
  # that lost its version injection, which would otherwise install silently and
  # read platform content from the working directory.
  test do
    assert_equal version.to_s, shell_output("#{bin}/kakt bundle-version").strip
  end
end
FORMULA

# The tap's own README, so a repository holding one generated file says what it
# is and how to use it. Refreshed with the formula, because the version it
# installs is stated in it.
#
# A QUOTED heredoc, with the version substituted afterwards: unquoted, every
# backtick in the markdown starts a command substitution, and escaping them put
# literal backslashes in the rendered page.
cat > "$work/tap/README.md" <<'README'
# Homebrew tap for `kakt`

```bash
brew install kamarkat/tap/kakt
kakt bundle-version
kakt box init
```

Currently `kakt @VERSION@`. The formula is generated by
`scripts/package/update-homebrew-tap.sh` in
[kamarkat/kamarkat](https://github.com/kamarkat/kamarkat) when a stable version
is released, and installs that release's published binary, verified against the
`sha256` the release publishes. Edits made here are overwritten.

Installing or upgrading the CLI does not upgrade a platform. A box runs the
bundle version its own repository declares until its owner adopts a change.
README
sed -i.bak "s/@VERSION@/${VERSION}/" "$work/tap/README.md" && rm -f "$work/tap/README.md.bak"

cd "$work/tap"

# STAGED FIRST, then compared. `git diff` ignores an untracked file, so on a tap
# that does not have the formula yet -- the first run against a new tap -- the
# comparison reported no change and the formula was never committed.
git add -- Formula/kakt.rb README.md
if git diff --cached --quiet -- Formula/kakt.rb README.md; then
    echo "homebrew-tap: ${TAP_REPO} already names ${VERSION}; nothing to push."
    exit 0
fi

git -c user.name="kamarkat release" -c user.email="noreply@kamarkat.invalid" \
    commit -q -m "kakt ${VERSION}" -- Formula/kakt.rb README.md
git push -q origin HEAD
echo "homebrew-tap: ${TAP_REPO} now installs kakt ${VERSION}"
echo "  brew install ${TAP_REPO%/*}/tap/kakt"
